/// <reference types="node" />
/**
 * Generates TypeScript theme files from src/tokens/tokens.json (exported from Figma).
 *
 *   npm run tokens
 *
 * Output:
 *   src/tokens/theme.ts               the `theme` object (Semantic, Typography, Motion + component tokens)
 *   src/tokens/components/<name>.ts   one file per component (Component collection + size collections)
 *
 * Paths follow each variable's Figma code syntax, e.g. `theme.color.text.primary`.
 * Rules:
 *   - `/font-style` variables are skipped (Figma only; use fontWeight).
 *   - `.../opacity` values are divided by 100 (80 → 0.8).
 *   - `border-width/separator` becomes `StyleSheet.hairlineWidth`.
 *   - fontWeight is emitted as a string ('600'), as React Native expects.
 *   - fontFamily "SF Pro" is left unset on iOS (system font) and uses the system font stack on web.
 *   - Easing strings ("0.2, 0, 0, 1") become number arrays for Easing.bezier.
 *   - Numbers are rounded to 3 decimals to remove Figma float noise.
 *   - Collections with several modes get one key per mode: componentSize.icon['16'].size.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS_DIR = join(ROOT, 'src/tokens');
const COMPONENTS_DIR = join(TOKENS_DIR, 'components');
const HEADER = '// AUTO-GENERATED by scripts/build-tokens.ts from src/tokens/tokens.json. Do not edit by hand.\n';

// ---------- types ----------

type Raw = number | string | boolean;
type Variable = {
  name: string;
  codeSyntax: string | null;
  type: 'color' | 'number' | 'string';
  value?: Raw;
  valuesByMode?: Record<string, Raw>;
};
type Collection = { hidden: boolean; modes: string[]; variables: Variable[] };
type TokensFile = { collections: Record<string, Collection> };

/** A raw code expression to emit as-is (not as a string literal). */
class Expr {
  code: string;
  constructor(code: string) {
    this.code = code;
  }
}
type Leaf = number | string | number[] | Expr;
type Tree = { [key: string]: Tree | Leaf };

// ---------- config ----------

/** Collections that become the top level of `theme`. */
const THEME_COLLECTIONS = ['Semantic', 'Typography', 'Motion'];
/** The Component collection: split into one file per component, exposed as `theme.component`. */
const COMPONENT_COLLECTION = 'Component';
/** Size collections: one per component, exposed as `theme.componentSize.<name>[mode]`. */
const SIZE_COLLECTIONS: Record<string, string> = {
  'Button Size': 'button',
  'Icon Button Size': 'icon-button',
  'Icon Container Size': 'icon-container',
  'Illustration Container Size': 'illustration-container',
  'Icon Size': 'icon',
};

const WEB_SYSTEM_FONT = '-apple-system, BlinkMacSystemFont, "SF Pro Text", system-ui, sans-serif';

/** Which component file a Component-collection variable belongs to, from its Figma name. */
function componentGroup(name: string): string {
  const [category, part, sub] = name.split('/');
  if (category === 'vehicle-card') return 'vehicle-card';
  if (category === 'border-width') return 'icon'; // border-width/icon-sm|md|lg
  if (category === 'color' && part === 'action') {
    if (sub === 'icon-button') return 'icon-button';
    if (sub === 'compact') return 'compact-button';
    return 'button'; // primary, secondary, tertiary, destructive
  }
  if (part === 'field') return 'text-field';
  if (category === 'radius' && (part === 'surface' || part === 'card')) return 'common';
  return part;
}

// ---------- helpers ----------

const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const exportName = (group: string) => `${camel(group)}Tokens`;
const isIdent = (k: string) => /^[A-Za-z_$][\w$]*$/.test(k);
const accessor = (path: string[]) => path.map((k) => (isIdent(k) ? `.${k}` : `['${k}']`)).join('');
const round = (n: number) => Math.round(n * 1000) / 1000;
const isBranch = (v: unknown): v is Tree =>
  typeof v === 'object' && v !== null && !Array.isArray(v) && !(v instanceof Expr);

/** Parses `theme.space.screen['2xl']` → ['space','screen','2xl']. `[size]` is replaced by the mode name. */
function parseCodeSyntax(code: string, mode?: string): string[] {
  const body = code.replace(/^theme\./, '');
  const parts: string[] = [];
  const re = /\.?([A-Za-z_$][\w$]*)|\['([^']+)'\]|\[(size)\]/g;
  let m: RegExpExecArray | null;
  let consumed = 0;
  while ((m = re.exec(body))) {
    if (m.index !== consumed) break;
    consumed = re.lastIndex;
    if (m[1]) parts.push(m[1]);
    else if (m[2]) parts.push(m[2]);
    else {
      if (mode === undefined) throw new Error(`"[size]" in ${code} but no mode given`);
      parts.push(mode);
    }
  }
  if (consumed !== body.length) throw new Error(`Cannot parse code syntax: ${code}`);
  return parts;
}

function setPath(tree: Tree, path: string[], value: Tree | Leaf, label: string) {
  let node = tree;
  path.slice(0, -1).forEach((key) => {
    const next = node[key];
    if (next === undefined) node[key] = {};
    else if (!isBranch(next)) throw new Error(`Path conflict at "${key}" for ${label}`);
    node = node[key] as Tree;
  });
  const last = path[path.length - 1];
  if (last in node) throw new Error(`Duplicate token path ${path.join('.')} (${label})`);
  node[last] = value;
}

function transform(v: Variable, raw: Raw, path: string[]): Leaf {
  const key = path[path.length - 1];
  if (typeof raw === 'boolean') throw new Error(`Boolean variables are not supported: ${v.name}`);
  if (key === 'opacity' && typeof raw === 'number') return round(raw / 100);
  if (key === 'fontWeight') return String(raw);
  if (key === 'fontFamily') return raw === 'SF Pro' ? new Expr('systemFontFamily') : raw;
  if (path.includes('easing') && typeof raw === 'string') return raw.split(',').map((n) => Number(n.trim()));
  if (typeof raw === 'number') return round(raw);
  return raw;
}

// ---------- serialisation ----------

function serialize(value: Tree | Leaf, indent = ''): string {
  if (value instanceof Expr) return value.code;
  if (Array.isArray(value)) return `[${value.join(', ')}]`;
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value === 'number') return String(value);
  const inner = indent + '  ';
  const lines = Object.entries(value).map(
    ([k, v]) => `${inner}${isIdent(k) ? k : `'${k}'`}: ${serialize(v, inner)},`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

/** Ownership tree: every leaf is the group name that owns it. */
type OwnerTree = { [key: string]: OwnerTree | string };

function owners(node: OwnerTree | string): Set<string> {
  if (typeof node === 'string') return new Set([node]);
  const out = new Set<string>();
  Object.values(node).forEach((child) => owners(child).forEach((o) => out.add(o)));
  return out;
}

/** Emits `theme.component` as references into the component files, collapsing subtrees owned by one file. */
function serializeOwned(node: OwnerTree, path: string[] = [], indent = '  '): string {
  const inner = indent + '  ';
  const lines = Object.entries(node).map(([k, child]) => {
    const childPath = [...path, k];
    const o = owners(child);
    const value =
      o.size === 1
        ? `${exportName([...o][0])}${accessor(childPath)}`
        : serializeOwned(child as OwnerTree, childPath, inner);
    return `${inner}${isIdent(k) ? k : `'${k}'`}: ${value},`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

// ---------- build ----------

const tokens: TokensFile = JSON.parse(readFileSync(join(TOKENS_DIR, 'tokens.json'), 'utf8'));
const theme: Tree = {};
const groups = new Map<string, Tree>();
const componentOwners: OwnerTree = {};
const sizeGroups: Record<string, string> = {}; // theme.componentSize key → group
let skipped = 0;
let count = 0;

const groupTree = (g: string) => {
  if (!groups.has(g)) groups.set(g, {});
  return groups.get(g)!;
};

for (const [collectionName, collection] of Object.entries(tokens.collections)) {
  const isTheme = THEME_COLLECTIONS.includes(collectionName);
  const isComponent = collectionName === COMPONENT_COLLECTION;
  const sizeGroup = SIZE_COLLECTIONS[collectionName];
  if (!isTheme && !isComponent && !sizeGroup) {
    console.warn(`⚠ Skipping unknown collection "${collectionName}". Add it to build-tokens.ts config.`);
    continue;
  }

  for (const v of collection.variables) {
    if (v.name.endsWith('/font-style')) {
      skipped++;
      continue;
    }

    // Special case: separator width is the device hairline.
    if (v.name === 'border-width/separator') {
      setPath(theme, ['borderWidth', 'separator'], new Expr('StyleSheet.hairlineWidth'), v.name);
      count++;
      continue;
    }

    if (!v.codeSyntax?.startsWith('theme.')) throw new Error(`Missing theme code syntax for ${v.name}`);

    if (isTheme) {
      const path = parseCodeSyntax(v.codeSyntax);
      setPath(theme, path, transform(v, v.value!, path), v.name);
    } else if (isComponent) {
      const path = parseCodeSyntax(v.codeSyntax);
      if (path[0] !== 'component') throw new Error(`Expected theme.component.* for ${v.name}`);
      const rest = path.slice(1);
      const group = componentGroup(v.name);
      setPath(groupTree(group), rest, transform(v, v.value!, rest), v.name);
      setPath(componentOwners as Tree, rest, group, v.name);
    } else {
      // Size collection: theme.componentSize.<key>[size].<prop> → <group>Tokens.size[mode].<prop>
      const values = v.valuesByMode ?? { [collection.modes[0]]: v.value! };
      for (const [mode, raw] of Object.entries(values)) {
        const path = parseCodeSyntax(v.codeSyntax, mode);
        if (path[0] !== 'componentSize') throw new Error(`Expected theme.componentSize.* for ${v.name}`);
        sizeGroups[path[1]] = sizeGroup;
        const rest = ['size', ...path.slice(2)];
        setPath(groupTree(sizeGroup), rest, transform(v, raw, rest), `${v.name} (${mode})`);
      }
    }
    count++;
  }
}

// Component files
rmSync(COMPONENTS_DIR, { recursive: true, force: true });
mkdirSync(COMPONENTS_DIR, { recursive: true });
const groupNames = [...groups.keys()].sort();
for (const g of groupNames) {
  const body = serialize(groups.get(g)!);
  if (body.includes('new Expr') || /systemFontFamily|StyleSheet/.test(body)) {
    throw new Error(`Component file ${g} needs an expression; not supported`);
  }
  writeFileSync(join(COMPONENTS_DIR, `${g}.ts`), `${HEADER}\nexport const ${exportName(g)} = ${body} as const;\n`);
}

// theme.ts
const imports = groupNames.map((g) => `import { ${exportName(g)} } from './components/${g}';`).join('\n');
const themeBody = serialize(theme).replace(/\n}$/, '');
const componentBody = serializeOwned(componentOwners);
const sizeBody = Object.entries(sizeGroups)
  .map(([key, g]) => `    ${isIdent(key) ? key : `'${key}'`}: ${exportName(g)}.size,`)
  .join('\n');

const themeFile = `${HEADER}
import { Platform, StyleSheet } from 'react-native';
${imports}

/** iOS: no fontFamily, so the system font (SF Pro) is used. Web preview: the system font stack. */
const systemFontFamily = Platform.select<string | undefined>({
  web: '${WEB_SYSTEM_FONT.replace(/'/g, "\\'")}',
  default: undefined,
});

export const theme = ${themeBody}
  component: ${componentBody},
  componentSize: {
${sizeBody}
  },
} as const;

export type Theme = typeof theme;
`;
writeFileSync(join(TOKENS_DIR, 'theme.ts'), themeFile);

console.log(`✓ ${count} tokens → src/tokens/theme.ts + ${groupNames.length} component files (${skipped} font-style skipped)`);
